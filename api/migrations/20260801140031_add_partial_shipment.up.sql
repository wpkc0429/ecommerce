-- change partial-shipment: 出貨的粒度從「整筆訂單、至多一筆」變成「訂單品項、可多筆」。
--
-- Hand-fixed (per cmd/migrategen's documented caveat, same as every sibling
-- change before it): the raw atlas diff again proposed dropping the handwritten
-- constraints the ent schema cannot express — members' UNIQUE(shop_id, email)
-- and UNIQUE(shop_id, phone) (20260730152723_member_identity_per_shop) and
-- role_user/user_permission's UNIQUE NULLS NOT DISTINCT
-- (20260718063900_rbac_unique_nulls_not_distinct). Those four DROP statements
-- were removed from this file, and their re-CREATE counterparts from the
-- .down.sql.
--
-- **No CHECK expression is amended by this change.**
-- order_items_shipped_quantity_check is new, on a new column; nothing existing
-- is redefined. atlas compares CHECK constraints by name and stays completely
-- silent about a changed expression (see 20260801054352_add_tier_discount for
-- the time that bit), so that caveat does not arise here — but the next person
-- amending one still has to write the DROP/ADD pair by hand.
--
-- **The index drop, by contrast, atlas did emit** (shipments.order_id UNIQUE →
-- plain). It was verified line by line rather than assumed; the generator runs
-- with WithDropIndex(true), which is why it appeared.
--
-- ── Why the backfill at the bottom is not optional ────────────────────
--
-- orders.fulfillment_status stops being a value somebody writes and becomes a
-- value derived from the order's shipments (design D2):
--
--   no shipments → 0 · any returned → 3 · shipped < ordered → 4 ·
--   all delivered → 2 · otherwise → 1
--
-- A pre-existing shipment has no shipment_items, and its order_items would have
-- shipped_quantity = 0 — so it would fall into the "shipped < ordered" branch,
-- and an order that has genuinely been delivered would re-derive as 4 (部分出貨)
-- the next time anything touched it. The backfill encodes the historical
-- semantics — "that one shipment was the whole order" — into the new model,
-- after which **every pre-existing order's derived value equals its stored
-- value**. That is asserted by an integration test, not merely intended here.

-- ── order_items: the only mutable column on the table (design D3) ─────
-- Its own statement, ahead of the constraint below: the check references a
-- column that has to exist first.
ALTER TABLE "order_items" ADD COLUMN "shipped_quantity" integer NOT NULL DEFAULT 0;

-- The second, independent arbiter behind the conditional UPDATE that increments
-- it. A mistyped predicate aborts the transaction here instead of writing an
-- impossible number that nothing would ever notice.
ALTER TABLE "order_items"
    ADD CONSTRAINT "order_items_shipped_quantity_check"
    CHECK ((shipped_quantity >= 0) AND (shipped_quantity <= quantity));

-- ── shipments: one order, many parcels ────────────────────────────────
-- The UNIQUE index that used to be the "at most one shipment per order" arbiter
-- becomes a plain lookup index. What replaced it is a different question
-- entirely — not "has this order shipped" but "is there anything left to ship" —
-- and its arbiter is order_items.shipped_quantity's conditional UPDATE plus the
-- CHECK above.
DROP INDEX "shipment_order_id";
CREATE INDEX "shipment_order_id" ON "shipments" ("order_id");

-- ── shipment_items: what is in the parcel ─────────────────────────────
-- No money column, deliberately: shipping fees live once, on the order
-- (orders.shipping_fee). A per-parcel amount would create a second authority for
-- what the customer was charged, with nothing reconciling the two.
CREATE TABLE "shipment_items" (
    "id" bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    "created_at" timestamptz NOT NULL,
    "updated_at" timestamptz NOT NULL,
    "quantity" integer NOT NULL,
    "shipment_id" bigint NOT NULL,
    "shop_id" bigint NOT NULL,
    "order_item_id" bigint NOT NULL,
    PRIMARY KEY ("id"),
    CONSTRAINT "shipment_items_order_items_order_item" FOREIGN KEY ("order_item_id") REFERENCES "order_items" ("id") ON UPDATE NO ACTION ON DELETE NO ACTION,
    CONSTRAINT "shipment_items_shipments_items" FOREIGN KEY ("shipment_id") REFERENCES "shipments" ("id") ON UPDATE NO ACTION ON DELETE CASCADE,
    CONSTRAINT "shipment_items_shops_shop" FOREIGN KEY ("shop_id") REFERENCES "shops" ("id") ON UPDATE NO ACTION ON DELETE NO ACTION,
    CONSTRAINT "shipment_items_quantity_check" CHECK (quantity > 0)
);
-- One line per order item per parcel. Standard Postgres uniqueness (NULLS
-- DISTINCT) and no NULL can reach it — both columns are NOT NULL. Do NOT add
-- NULLS NOT DISTINCT here; that spelling belongs to site_shop/role_user/
-- user_permission and answers a different question.
CREATE UNIQUE INDEX "shipmentitem_shipment_id_order_item_id" ON "shipment_items" ("shipment_id", "order_item_id");
-- Tenant-scoped lookup ("what was in this shop's parcel").
CREATE INDEX "shipmentitem_shop_id_shipment_id" ON "shipment_items" ("shop_id", "shipment_id");

-- ── backfill (see the header comment) ─────────────────────────────────
-- Every pre-existing shipment covered its whole order, so give it exactly that.
INSERT INTO "shipment_items" ("created_at", "updated_at", "quantity", "shipment_id", "shop_id", "order_item_id")
SELECT now(), now(), oi."quantity", s."id", oi."shop_id", oi."id"
FROM "shipments" s
JOIN "order_items" oi ON oi."order_id" = s."order_id";

UPDATE "order_items" oi
SET "shipped_quantity" = oi."quantity"
WHERE EXISTS (SELECT 1 FROM "shipments" s WHERE s."order_id" = oi."order_id");
