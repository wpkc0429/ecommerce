-- ── Data migration (change headless-content-store slice 2, design D1) ──────
-- Additive: pages and shops.content_json stay exactly as they are and keep
-- being written (internal/contentstore keeps both sides equal in one
-- transaction). Every statement is idempotent.

-- 1. Refuse slugs that cannot be content keys. Expected: zero rows.
DO $$
DECLARE bad text;
BEGIN
  SELECT string_agg(p.id::text || ':' || p.slug, ', ') INTO bad
  FROM pages p
  WHERE p.slug !~ '^[a-z0-9][a-z0-9-]{0,62}$' OR p.slug = 'global';
  IF bad IS NOT NULL THEN
    RAISE EXCEPTION 'content_documents backfill: these pages (id:slug) cannot become content keys (must match ^[a-z0-9][a-z0-9-]{0,62}$, and "global" is reserved): %', bad;
  END IF;
END $$;

-- 2. pages -> content_documents (slug -> key; the rest is the identity).
INSERT INTO content_documents
  (shop_id, key, type_key, title, status, draft_json, published_json, meta,
   draft_rev, published_rev, schema_version, published_schema_version,
   needs_attention, declared, created_at, updated_at, published_at)
SELECT p.shop_id, p.slug, p.type_key, p.title, p.status, p.content_json, p.published_json, p.meta,
       1, CASE WHEN p.published_json IS NOT NULL THEN 1 ELSE 0 END,
       COALESCE(v.version, 0), CASE WHEN p.published_json IS NOT NULL THEN COALESCE(v.version, 0) ELSE 0 END,
       p.needs_attention, true, p.created_at, p.updated_at,
       CASE WHEN p.status = 1 THEN p.updated_at END
FROM pages p
LEFT JOIN LATERAL (SELECT max(cs.version) AS version FROM content_schemas cs WHERE cs.shop_id = p.shop_id) v ON true
ON CONFLICT (shop_id, key) DO NOTHING;

-- 3. shops.content_json -> the document "global" (published = draft, so it
--    stays live exactly as it is today).
INSERT INTO content_documents
  (shop_id, key, type_key, title, status, draft_json, published_json, meta,
   draft_rev, published_rev, schema_version, published_schema_version,
   needs_attention, declared, created_at, updated_at, published_at)
SELECT s.id, 'global', 'global', 'Global', 1, s.content_json, s.content_json, '{}'::jsonb,
       1, 1, COALESCE(v.version, 0), COALESCE(v.version, 0),
       false, true, s.created_at, s.updated_at, s.updated_at
FROM shops s
LEFT JOIN LATERAL (SELECT max(cs.version) AS version FROM content_schemas cs WHERE cs.shop_id = s.id) v ON true
ON CONFLICT (shop_id, key) DO NOTHING;

-- 4. One 'publish' revision for every document that has published content.
INSERT INTO content_revisions
  (shop_id, document_id, rev_no, kind, json, title, meta, schema_version, created_at)
SELECT d.shop_id, d.id, 1, 'publish', d.published_json, d.title, d.meta, d.published_schema_version, COALESCE(d.published_at, d.updated_at)
FROM content_documents d
WHERE d.published_json IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM content_revisions r WHERE r.document_id = d.id);

-- 5. Slice-1 interim storage moves into the proper tables.
--    content_schemas.snapshot_json -> content_revisions(kind='schema_snapshot').
--    The columns content_schemas.snapshot_json and created_by_user_id are kept
--    (deprecated, no longer written); dropping them belongs to the clean-up group.
INSERT INTO content_revisions
  (shop_id, document_id, rev_no, kind, json, published_json, title, meta, schema_version, created_at)
SELECT cs.shop_id, d.id,
       (SELECT COALESCE(max(r.rev_no), 0) FROM content_revisions r WHERE r.document_id = d.id)
         + row_number() OVER (PARTITION BY d.id ORDER BY cs.version),
       'schema_snapshot', e.entry -> 'draft', e.entry -> 'published', d.title, d.meta, cs.version, cs.created_at
FROM content_schemas cs
CROSS JOIN LATERAL jsonb_array_elements(cs.snapshot_json -> 'documents') AS e(entry)
JOIN content_documents d ON d.shop_id = cs.shop_id AND d.key = e.entry ->> 'key'
WHERE cs.snapshot_json IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM content_revisions r
                  WHERE r.document_id = d.id AND r.kind = 'schema_snapshot' AND r.schema_version = cs.version);

--    content_schemas.created_by_user_id -> content_audit_log(action='schema.register').
INSERT INTO content_audit_log (shop_id, actor_user_id, action, doc_key, detail, created_at)
SELECT cs.shop_id, cs.created_by_user_id, 'schema.register', '',
       jsonb_build_object('schema_version', cs.version, 'backfilled', true), cs.created_at
FROM content_schemas cs
WHERE cs.source = 'registered'
  AND NOT EXISTS (SELECT 1 FROM content_audit_log a
                  WHERE a.shop_id = cs.shop_id AND a.action = 'schema.register'
                    AND a.detail ->> 'schema_version' = cs.version::text);
