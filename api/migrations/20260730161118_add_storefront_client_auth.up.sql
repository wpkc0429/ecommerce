-- change storefront-client-auth (design D4/D5): purely additive — two new
-- shop-owned tables, no data movement, no changes to existing columns.
--
-- The Atlas diff also proposed dropping "uq_members_shop_email",
-- "uq_members_shop_phone", "uq_role_user_user_role_shop" and
-- "uq_user_permission_user_perm_shop"; those are hand-written constraints the
-- ent schema cannot express (per-shop nullable uniqueness / UNIQUE NULLS NOT
-- DISTINCT) and the diff engine does not know about them. Removed by hand, per
-- the convention documented in cmd/migrategen.

-- create "publishable_keys" table
CREATE TABLE "publishable_keys" ("id" bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY, "key" character varying(64) NOT NULL, "label" character varying(100) NOT NULL DEFAULT '', "created_at" timestamptz NOT NULL, "revoked_at" timestamptz NULL, "shop_id" bigint NOT NULL, PRIMARY KEY ("id"), CONSTRAINT "publishable_keys_shops_shop" FOREIGN KEY ("shop_id") REFERENCES "shops" ("id") ON UPDATE NO ACTION ON DELETE NO ACTION);
-- create index "publishable_keys_key_key" to table: "publishable_keys"
CREATE UNIQUE INDEX "publishable_keys_key_key" ON "publishable_keys" ("key");
-- create index "publishablekey_shop_id" to table: "publishable_keys"
CREATE INDEX "publishablekey_shop_id" ON "publishable_keys" ("shop_id");
-- create "shop_allowed_origins" table
CREATE TABLE "shop_allowed_origins" ("id" bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY, "origin" character varying(255) NOT NULL, "created_at" timestamptz NOT NULL, "shop_id" bigint NOT NULL, PRIMARY KEY ("id"), CONSTRAINT "shop_allowed_origins_shops_shop" FOREIGN KEY ("shop_id") REFERENCES "shops" ("id") ON UPDATE NO ACTION ON DELETE NO ACTION);
-- create index "shop_allowed_origins_origin_key" to table: "shop_allowed_origins"
CREATE UNIQUE INDEX "shop_allowed_origins_origin_key" ON "shop_allowed_origins" ("origin");
-- create index "shopallowedorigin_shop_id" to table: "shop_allowed_origins"
CREATE INDEX "shopallowedorigin_shop_id" ON "shop_allowed_origins" ("shop_id");
