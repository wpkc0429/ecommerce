-- reverse of change member-identity-per-shop: rebuild shop_member, move the
-- loyalty columns back onto it, restore point_transactions.shop_member_id and
-- the platform-wide member uniqueness. Steps run in the exact reverse order of
-- the .up.sql's 7 steps.
--
-- KNOWN LIMITATION (design Migration Plan / Rollback): this cannot restore the
-- *merged* semantics of a cross-shop identity. Going down, two per-shop members
-- rows sharing one email stay two separate platform identities, and restoring
-- the global UNIQUE(email)/UNIQUE(phone) at the end then fails outright. That
-- is intentional — silently merging two rows with different password hashes,
-- statuses and point balances would be worse than refusing. It is safe today
-- because no such data exists (verified: 0 cross-shop identities), and any
-- future rollback past this point needs a purpose-written data script first.
--
-- Hand-fixed like the .up.sql: the raw atlas diff's DROP/re-ADD of
-- role_user/user_permission's handwritten UNIQUE NULLS NOT DISTINCT
-- constraints was removed (they were never touched going up).

-- ── Reverse step 7: recreate shop_member ──────────────────────────────
CREATE TABLE "shop_member" (
    "id" bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    "created_at" timestamptz NOT NULL,
    "updated_at" timestamptz NOT NULL,
    "points" integer NOT NULL DEFAULT 0,
    "level_id" bigint NULL,
    "shop_id" bigint NOT NULL,
    "member_id" bigint NOT NULL,
    PRIMARY KEY ("id"),
    CONSTRAINT "shop_member_members_member" FOREIGN KEY ("member_id") REFERENCES "members" ("id") ON UPDATE NO ACTION ON DELETE NO ACTION,
    CONSTRAINT "shop_member_shops_shop" FOREIGN KEY ("shop_id") REFERENCES "shops" ("id") ON UPDATE NO ACTION ON DELETE NO ACTION,
    CONSTRAINT "shop_member_member_tiers_member_tier" FOREIGN KEY ("level_id") REFERENCES "member_tiers" ("id") ON UPDATE NO ACTION ON DELETE SET NULL
);
CREATE INDEX "shopmember_member_id" ON "shop_member" ("member_id");
CREATE UNIQUE INDEX "shopmember_shop_id_member_id" ON "shop_member" ("shop_id", "member_id");

-- One membership row per per-shop identity (the inverse of the up migration's
-- 1:1 expansion).
INSERT INTO "shop_member" ("created_at", "updated_at", "points", "level_id", "shop_id", "member_id")
SELECT "created_at", "updated_at", "points", "level_id", "shop_id", "id" FROM "members";

-- ── Reverse step 6: point_transactions.member_id → shop_member_id ─────
ALTER TABLE "point_transactions" DROP CONSTRAINT "point_transactions_members_member";
DROP INDEX "pointtransaction_shop_id_member_id";
ALTER TABLE "point_transactions" RENAME COLUMN "member_id" TO "shop_member_id";
UPDATE "point_transactions" pt
SET "shop_member_id" = sm."id"
FROM "shop_member" sm
WHERE sm."member_id" = pt."shop_member_id" AND sm."shop_id" = pt."shop_id";
ALTER TABLE "point_transactions"
    ADD CONSTRAINT "point_transactions_shop_member_shop_member" FOREIGN KEY ("shop_member_id") REFERENCES "shop_member" ("id") ON UPDATE NO ACTION ON DELETE NO ACTION;
CREATE INDEX "pointtransaction_shop_id_shop_member_id" ON "point_transactions" ("shop_id", "shop_member_id");

-- ── Reverse step 5: per-shop uniqueness → platform-wide uniqueness ────
DROP INDEX "uq_members_shop_email";
DROP INDEX "uq_members_shop_phone";

-- ── Reverse steps 4/3/1: members sheds shop_id and the loyalty columns ─
DROP INDEX "member_shop_id";
ALTER TABLE "members"
    DROP CONSTRAINT "members_shops_shop",
    DROP CONSTRAINT "members_member_tiers_member_tier",
    DROP COLUMN "level_id",
    DROP COLUMN "shop_id",
    DROP COLUMN "points";

-- Fails if two shops shared an email/phone — see the KNOWN LIMITATION above.
CREATE UNIQUE INDEX "members_email_key" ON "members" ("email");
CREATE UNIQUE INDEX "members_phone_key" ON "members" ("phone");
