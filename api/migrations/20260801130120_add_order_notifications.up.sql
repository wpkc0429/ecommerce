-- change order-notification-email: the table that decides whether a customer
-- email has already been sent for one order (design D6/D13/D16).
--
-- Hand-fixed (per cmd/migrategen's documented caveat, same as every sibling
-- change before it): the raw atlas diff again proposed dropping the handwritten
-- constraints the ent schema cannot express — members' UNIQUE(shop_id, email)
-- and UNIQUE(shop_id, phone) (20260730152723_member_identity_per_shop) and
-- role_user/user_permission's UNIQUE NULLS NOT DISTINCT
-- (20260718063900_rbac_unique_nulls_not_distinct). Those DROP statements were
-- removed from this file, and their re-CREATE counterparts from the .down.sql.
--
-- **No CHECK expression is amended by this change** — the two CHECKs below are
-- new, on a new table. atlas compares CHECK constraints by name and stays
-- completely silent about a changed expression, so amending one always has to be
-- handwritten; that caveat simply does not arise here.
--
-- No backfill, and deliberately so: an empty table means "no email has been sent
-- for any existing order", which is exactly true. Back-filling rows for
-- historical orders would claim we contacted customers we never contacted.
--
-- ── Why UNIQUE(order_id, kind) is the load-bearing line ────────────────
--
-- payment.Service.HandleWebhook publishes its success event on EVERY delivery
-- that re-confirms an already-succeeded payment, not only the first, and 綠界
-- redelivers up to 4 times a day when it does not receive `1|OK`. This index —
-- not any application-level read-then-write — is what stops a customer receiving
-- the same email twice. Same idiom as point_transactions(order_id, kind),
-- payments(provider, provider_reference), shipments(order_id).
--
-- Standard Postgres uniqueness (NULLS DISTINCT), and no NULL can reach it: both
-- columns are NOT NULL. Do NOT add NULLS NOT DISTINCT here — that spelling
-- belongs to site_shop/role_user/user_permission and answers a different
-- question.

-- ── order_notifications ───────────────────────────────────────────────
CREATE TABLE "order_notifications" (
    "id" bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    "created_at" timestamptz NOT NULL,
    "updated_at" timestamptz NOT NULL,
    "kind" smallint NOT NULL,
    "recipient_email" character varying(150) NOT NULL,
    "status" smallint NOT NULL DEFAULT 0,
    "sent_at" timestamptz NULL,
    "error_reason" character varying(500) NULL,
    "shop_id" bigint NOT NULL,
    "order_id" bigint NOT NULL,
    PRIMARY KEY ("id"),
    CONSTRAINT "order_notifications_orders_order" FOREIGN KEY ("order_id") REFERENCES "orders" ("id") ON UPDATE NO ACTION ON DELETE NO ACTION,
    CONSTRAINT "order_notifications_shops_shop" FOREIGN KEY ("shop_id") REFERENCES "shops" ("id") ON UPDATE NO ACTION ON DELETE NO ACTION,
    CONSTRAINT "order_notifications_kind_check" CHECK (kind = ANY (ARRAY[0, 1])),
    CONSTRAINT "order_notifications_status_check" CHECK (status = ANY (ARRAY[0, 1, 2]))
);
-- The duplicate-send arbiter — see the header comment.
CREATE UNIQUE INDEX "ordernotification_order_id_kind" ON "order_notifications" ("order_id", "kind");
-- Tenant-scoped lookup ("what did we send for this shop's order").
CREATE INDEX "ordernotification_shop_id_order_id" ON "order_notifications" ("shop_id", "order_id");
