-- change retire-hosted-storefront-and-themes (group 1): per-shop content schemas.
--
-- Page and global-content validation stops reading themes/theme_pages and reads
-- the shop's own schema version instead (first slice of headless-content-store).
-- This migration only ADDS a table and copies data; nothing is dropped.
-- create "content_schemas" table
CREATE TABLE "content_schemas" ("id" bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY, "version" bigint NOT NULL, "schema_json" jsonb NOT NULL, "sha256" character varying(64) NOT NULL, "source" character varying(30) NOT NULL, "created_at" timestamptz NOT NULL, "shop_id" bigint NOT NULL, PRIMARY KEY ("id"), CONSTRAINT "content_schemas_shops_shop" FOREIGN KEY ("shop_id") REFERENCES "shops" ("id") ON UPDATE NO ACTION ON DELETE NO ACTION, CONSTRAINT "content_schemas_version_check" CHECK (version >= 1));
-- create index "contentschema_shop_id_version" to table: "content_schemas"
CREATE UNIQUE INDEX "contentschema_shop_id_version" ON "content_schemas" ("shop_id", "version");

-- Backfill: every shop that has a theme gets version 1 = a copy of that theme's
-- schemas (format 1, see ent/schema/contentschema.go):
--   types          <- theme_pages.page_schema keyed by type_key
--   type_order     <- type keys in theme_pages.id order (admin page-types order)
--   global         <- themes.config_schema
--   component_keys <- theme_pages.component_key keyed by type_key
-- sha256 here is the digest of the jsonb text form (Go-written versions use the
-- normalized-JSON digest; the Go store recomputes before comparing). Idempotent:
-- shops that already have a version are skipped.
INSERT INTO "content_schemas" ("shop_id", "version", "schema_json", "sha256", "source", "created_at")
SELECT s."id", 1, d."doc",
       encode(sha256(convert_to(d."doc"::text, 'UTF8')), 'hex'),
       'theme_backfill', now()
FROM "shops" s
JOIN "themes" t ON t."id" = s."theme_id"
CROSS JOIN LATERAL (
  SELECT jsonb_build_object(
    'format', 1,
    'types', COALESCE((SELECT jsonb_object_agg(tp."type_key", tp."page_schema") FROM "theme_pages" tp WHERE tp."theme_id" = t."id"), '{}'::jsonb),
    'type_order', COALESCE((SELECT jsonb_agg(tp."type_key" ORDER BY tp."id") FROM "theme_pages" tp WHERE tp."theme_id" = t."id"), '[]'::jsonb),
    'global', t."config_schema",
    'component_keys', COALESCE((SELECT jsonb_object_agg(tp."type_key", tp."component_key") FROM "theme_pages" tp WHERE tp."theme_id" = t."id"), '{}'::jsonb)
  ) AS "doc"
) d
WHERE s."theme_id" IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM "content_schemas" c WHERE c."shop_id" = s."id");
